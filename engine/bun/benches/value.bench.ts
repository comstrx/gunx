import * as value from "engine/value";
import { bench, do_not_optimize, run } from "mitata";

const price = value.money.of("1234.50", "EGP");
const basket = Array.from({ length: 32 }, ( _, index ) => value.money.minor(1999 + index, "EGP"));
const wire = value.money.toJson(price);
const prices = ["12.50", "7", "0.075", "1999.99", "250", "3.333", "18", "42.42"];

bench("value.integer text", () => do_not_optimize(value.integer("1,234,567")));
bench("value.integer arabic", () => do_not_optimize(value.integer("١٬٢٣٤٬٥٦٧")));
bench("value.number text", () => do_not_optimize(value.number("1,234.5")));
bench("value.boolean", () => do_not_optimize(value.boolean("yes")));
bench("value.date", () => do_not_optimize(value.date("2026-03-15T13:45:30.000Z")));
bench("value.list", () => do_not_optimize(value.list("red, green, blue, amber")));
bench("value.listOf", () => do_not_optimize(value.listOf("egp, usd, nope, sar", value.currency)));
bench("value.oneOf", () => do_not_optimize(value.oneOf("LIVE", ["draft", "live", "archived"])));
bench("value.scalar", () => do_not_optimize(value.scalar("12.5")));
bench("value.kind", () => do_not_optimize(value.kind("2026-03-15")));
bench("value.cast", () => do_not_optimize(value.cast("integer", "42")));
bench("value.email", () => do_not_optimize(value.email(" Ada.Lovelace+tag@Example.COM ")));
bench("value.url", () => do_not_optimize(value.url("https://example.com/a/b?q=1#top")));
bench("value.phone", () => do_not_optimize(value.phone("0100 000 0000", "+20")));
bench("value.slug", () => do_not_optimize(value.slug("Hello-World-2")));
bench("value.uuid", () => do_not_optimize(value.uuid("018F4E2A-7B1C-7C3D-9E4F-0A1B2C3D4E5F")));
bench("value.locale", () => do_not_optimize(value.locale("ar_eg")));
bench("value.plainDate", () => do_not_optimize(value.plainDate("2026-03-15")));
bench("value.decimal.of", () => do_not_optimize(value.decimal.of("1,234.5000")));
bench("value.decimal.add", () => do_not_optimize(value.decimal.add("1234.5", "0.075")));
bench("value.decimal.multiply", () => do_not_optimize(value.decimal.multiply("1234.5", "1.14")));
bench("value.decimal.divide", () => do_not_optimize(value.decimal.divide("1234.5", "7")));
bench("value.decimal.round", () => do_not_optimize(value.decimal.round("1234.56789", 2)));
bench("value.decimal.fixed", () => do_not_optimize(value.decimal.fixed("1234.5", 2)));
bench("value.decimal.compare", () => do_not_optimize(value.decimal.compare("1234.5", "1234.50001")));
bench("value.decimal.sum x8", () => do_not_optimize(value.decimal.sum(prices)));
bench("value.money.of number", () => do_not_optimize(value.money.of(1234.5, "EGP")));
bench("value.money.of text", () => do_not_optimize(value.money.of("1,234.50", "EGP")));
bench("value.money.minor", () => do_not_optimize(value.money.minor(123_450, "EGP")));
bench("value.money.parse", () => do_not_optimize(value.money.parse("EGP 1,234.50")));
bench("value.money.add", () => do_not_optimize(value.money.add(price, price)));
bench("value.money.multiply whole", () => do_not_optimize(value.money.multiply(price, 3)));
bench("value.money.multiply fraction", () => do_not_optimize(value.money.multiply(price, 1.155)));
bench("value.money.divide", () => do_not_optimize(value.money.divide(price, 7)));
bench("value.money.percent", () => do_not_optimize(value.money.percent(price, 14)));
bench("value.money.gross", () => do_not_optimize(value.money.gross(price, 14)));
bench("value.money.net", () => do_not_optimize(value.money.net(price, 14)));
bench("value.money.allocate x3", () => do_not_optimize(value.money.allocate(price, [50, 30, 20])));
bench("value.money.allocate wide", () => do_not_optimize(value.money.allocate(value.money.minor(Number.MAX_SAFE_INTEGER, "EGP"), [50, 30, 20])));
bench("value.money.split x12", () => do_not_optimize(value.money.split(price, 12)));
bench("value.money.total x32", () => do_not_optimize(value.money.total(basket)));
bench("value.money.convert", () => do_not_optimize(value.money.convert(price, "USD", "0.0201")));
bench("value.money.format", () => do_not_optimize(value.money.format(price)));
bench("value.money.toJson", () => do_not_optimize(value.money.toJson(price)));
bench("value.money.fromJson", () => do_not_optimize(value.money.fromJson(wire)));

await run();
