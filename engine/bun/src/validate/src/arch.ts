import type * as zod from "./zod.ts";

export type Schema<Out = unknown, In = unknown> = zod.ZodMiniType<Out, In>;
export type Issue = zod.core.$ZodIssue;
export type Context = zod.core.ParsePayload;
export type Check = zod.core.$ZodCheck<never>;
export type infer<T extends Schema> = zod.core.output<T>;
export type output<T extends Schema> = zod.core.output<T>;
export type input<T extends Schema> = zod.core.input<T>;
export type CheckRule = { check: string; type?: string; format?: string; pattern?: RegExp; minimum?: number; maximum?: number; length?: number; size?: number; value?: unknown; inclusive?: boolean };
export type Mark = { _zod: { def: CheckRule } };
export type Stamp = zod.core.$ZodCheck<unknown>;
export type Def = {
    type: string;
    format?: string | undefined;
    checks?: Mark[] | undefined;
    innerType?: Schema | undefined;
    in?: Schema | undefined;
    out?: Schema | undefined;
    shape?: Record<string, Schema> | undefined;
    entries?: Record<string, unknown> | undefined;
    values?: readonly unknown[] | undefined;
    options?: Schema[] | undefined;
    items?: Schema[] | undefined;
    element?: Schema | undefined;
    valueType?: Schema | undefined;
    getter?: (() => Schema) | undefined;
};
export type Found = { inner: Schema; optional: boolean; nullable: boolean; checks: Mark[]; notes: Facts[] };
export type Open = { above?: number; below?: number };
export type Facts = { format?: string; min?: number; max?: number; above?: number; below?: number; step?: number; values?: unknown[]; pattern?: RegExp };
export type Field = {
    name: string;
    kind: string;
    required: boolean;
    optional?: boolean | undefined;
    nullable?: boolean | undefined;
    min?: number | undefined;
    max?: number | undefined;
    above?: number | undefined;
    below?: number | undefined;
    step?: number | undefined;
    options?: string[] | undefined;
    values?: unknown[] | undefined;
    format?: string | undefined;
    pattern?: RegExp | undefined;
    fields?: Field[] | undefined;
    item?: Field | undefined;
    variants?: Field[] | undefined;
};
export type FileLike = { size: number; type: string; name?: string | undefined };
export type FileLimits = { maxBytes?: number | undefined; types?: readonly string[] | undefined; extensions?: readonly string[] | undefined };
export type RulesRule = { name: string; args: string[]; text: string };
export type Loose = Schema & { check: ( ...checks: Check[] ) => Schema };
export type Row = Record<string, unknown>;
export type Test = ( given: unknown ) => boolean;
export type Raw = { name: string; test: ( text: string ) => boolean };
export type Presence = { must: string | undefined; prohibited: boolean; filled: boolean; nullable: boolean; raws: Raw[] };
export type Built = { schema: Schema; plain: Schema; cross: RulesRule[]; found: RulesRule[] };
export type Cross = { test: ( row: Row ) => boolean; message: string };
export type Pending = { name: string; rule: RulesRule };
export type Order = ( own: number, other: number ) => boolean;
export type Rules = string | readonly string[];
export type Book = Record<string, Rules>;
