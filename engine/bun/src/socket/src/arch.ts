import type * as event from "engine-event";
import type * as exception from "engine-exception";
import type * as func from "engine-func";

export type Frame = { event: string; data?: unknown; channel?: string | undefined; id?: string | undefined };
export type Status = "idle" | "connecting" | "open" | "closed" | "failed";
export type Handler = ( data: unknown, frame: Frame ) => void;
export type Socket = {
    readyState: number;
    bufferedAmount?: number | undefined;
    send: ( text: string ) => void;
    close: ( code?: number, reason?: string ) => void;
    onopen: (() => void) | null;
    onclose: (( closing: { code: number; reason: string } ) => void) | null;
    onerror: (( failure: unknown ) => void) | null;
    onmessage: (( message: { data: unknown } ) => void) | null;
};
export type SocketFactory = ( url: string, protocols?: string | string[] ) => Socket;
export type Reconnect = {
    min?: number | undefined;
    max?: number | undefined;
    factor?: number | undefined;
    limit?: number | undefined;
    steady?: number | undefined;
    when?: (( code: number, reason: string ) => boolean) | undefined;
};
export type Ask = event.Wait & { channel?: string | undefined };
export type Stats = { sent: number; received: number; refused: number; opens: number };
export type Command = "ping" | "pong" | "join" | "leave";
export type Protocol = {
    encode: ( frame: Frame, command?: Command ) => string;
    decode: ( text: string ) => Frame | undefined;
    kind: ( frame: Frame ) => "ping" | "quiet" | "error" | "hello" | undefined;
    fault: ( frame: Frame ) => exception.Fault;
    identity: ( frame: Frame ) => string | undefined;
    ending?: (( code: number, reason: string ) => exception.Fault) | undefined;
    retry?: (( code: number, reason: string ) => boolean) | undefined;
};
export type Options = {
    protocol: Protocol;
    url: string | (() => string | Promise<string>);
    protocols?: string | string[] | undefined;
    prepare?: (() => string | undefined | Promise<string | undefined>) | undefined;
    reconnect?: Reconnect | false | undefined;
    heartbeat?: number | undefined;
    timeout?: number | undefined;
    maxFrame?: number | undefined;
    buffer?: number | undefined;
    backlog?: number | undefined;
    factory?: SocketFactory | undefined;
    fail?: event.Fail | undefined;
    onStatus?: (( status: Status, attempt: number ) => void) | undefined;
};
export type Connection = {
    status: () => Status;
    id: () => string | undefined;
    cause: () => exception.Fault | undefined;
    attempts: () => number;
    stats: () => Stats;
    channels: () => string[];
    joined: ( channel: string ) => boolean;
    connect: () => Promise<void>;
    close: ( code?: number, reason?: string ) => void;
    emit: ( name: string, data?: unknown, channel?: string ) => boolean;
    request: <T = unknown>( name: string, data?: unknown, options?: Ask ) => Promise<T>;
    on: ( name: string, handler: Handler, channel?: string ) => () => void;
    once: ( name: string, channel?: string, wait?: number | event.Wait ) => Promise<unknown>;
    watch: ( listener: ( status: Status, attempt: number ) => void ) => () => void;
    join: ( channel: string ) => Promise<void>;
    leave: ( channel: string ) => Promise<void>;
};
export type Frames = Record<string, Frame>;
export type Rows = event.Emitter<Frames>;
export type Timer = ReturnType<typeof setTimeout>;
export type Waiting = { resolve: ( frame: Frame ) => void; reject: ( cause: unknown ) => void; sent: boolean };
export type Held = { text: string; id: string | undefined };
export type Room = { joined: boolean; asking: number; gate: func.Deferred<void> | undefined };
export type Note = { status: Status; attempt: number };
export type Plan = { min: number; max: number; factor: number; limit: number; steady: number; when: ( code: number, reason: string ) => boolean };
export type Channel = {
    readonly name: string;
    joined: () => boolean;
    on: ( name: string, handler: Handler ) => () => void;
    once: ( name: string, wait?: number | event.Wait ) => Promise<unknown>;
    emit: ( name: string, data?: unknown ) => boolean;
    request: <T = unknown>( name: string, data?: unknown, wait?: number | event.Wait ) => Promise<T>;
    join: () => Promise<void>;
    leave: () => Promise<void>;
};
