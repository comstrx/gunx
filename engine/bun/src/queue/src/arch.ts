import type * as cache from "engine-cache";
import type * as exception from "engine-exception";

export type Backoff = { delay?: number | undefined; factor?: number | undefined; max?: number | undefined; jitter?: number | undefined };
export type Schedule = {
    every?: number | undefined;
    immediate?: boolean | undefined;
    when?: (() => boolean) | undefined;
    onFlush?: (( result: Outcome ) => void) | undefined;
    fail?: (( cause: unknown ) => void) | undefined;
};
export type Status = "pending" | "running" | "done" | "failed" | "dead";
export type Job<P = unknown> = {
    id: string;
    type: string;
    payload: P;
    owner: string;
    key: string | undefined;
    status: Status;
    attempts: number;
    at: number;
    available: number;
    error: string | undefined;
    code: string | undefined;
};
export type Perform = ( job: Job, signal: AbortSignal ) => Promise<void>;
export type Outcome = { done: number; failed: number };
export type Counts = Record<Status, number>;
export type Push = { key?: string | undefined; delay?: number | undefined };
export type Options = {
    name?: string | undefined;
    store?: cache.Storage | undefined;
    guard?: "shared" | "local" | undefined;
    owner: string;
    perform: Perform;
    retries?: number | undefined;
    delay?: number | undefined;
    factor?: number | undefined;
    backoff?: (( attempt: number ) => number) | undefined;
    when?: (( fault: exception.Fault, job: Job ) => boolean) | undefined;
    timeout?: number | undefined;
    lanes?: number | undefined;
    strict?: boolean | undefined;
    keep?: number | undefined;
    onChange?: (( jobs: Job[] ) => void) | undefined;
    fail?: (( cause: unknown ) => void) | undefined;
};
export type Outbox = {
    push: <P>( type: string, payload: P, options?: Push ) => Promise<Job<P>>;
    flush: ( signal?: AbortSignal ) => Promise<Outcome>;
    jobs: ( status?: Status ) => Promise<Job[]>;
    get: ( id: string ) => Promise<Job | undefined>;
    counts: () => Promise<Counts>;
    pending: () => Promise<number>;
    next: () => Promise<number | undefined>;
    retry: ( id: string ) => Promise<boolean>;
    replay: () => Promise<number>;
    drop: ( id: string ) => Promise<boolean>;
    prune: ( status?: "done" | "dead" ) => Promise<number>;
    clear: () => Promise<void>;
    watch: ( listener: ( jobs: Job[] ) => void ) => () => void;
    start: ( every?: number ) => void;
    stop: () => void;
    destroy: () => void;
    load: () => Promise<Job[]>;
};
export type End = "done" | "free" | "fail" | "dead";
export type Ended = { job: Job; fault: exception.Fault | undefined; end: End; wait: number };
export type Flight = { signal: AbortSignal | undefined; seen: Set<string>; tally: Outcome; failures: unknown[]; blocked: boolean };
